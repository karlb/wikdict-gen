def dict_dir():
    """Output root for all generated databases (raw/processed/infer/...).

    Defaults to ``dictionaries``; override with ``WIKDICT_DICT_DIR`` (e.g. to build
    into a temp dir for the end-to-end test). Resolved per call so a test can set
    the env var after import. Mirrors ``WIKDICT_STORE`` in sparql/store.py.
    """
    return os.environ.get("WIKDICT_DICT_DIR", "dictionaries")


def make_targets(
    lang, out_path, targets, in_path=None, only=None, sql=None, attach=(), vacuum=True
):
    if out_path.endswith(".sqlite3"):
        conn = sqlite3.connect("%s/%s" % (dict_dir(), out_path))
    else:
        os.makedirs("%s/%s" % (dict_dir(), out_path), exist_ok=True)
        conn = sqlite3.connect("%s/%s/%s.sqlite3" % (dict_dir(), out_path, lang))

    with closing(conn):
        # Enable loading SQLite extensions (needed for spellfix1)
        conn.enable_load_extension(True)

        try:
            conn.execute(
                "ATTACH DATABASE '%s/%s/%s.sqlite3' AS %s"
                % (dict_dir(), in_path, lang, in_path)
            )
        except sqlite3.dbapi2.OperationalError:
            print("Error attaching ", in_path, lang, "database")
            raise

        for a in attach:
            conn.execute("ATTACH DATABASE " + a)

        if sql:
            cur = conn.cursor()
            cur.execute(sql)
            from tabulate import tabulate

            print(tabulate(cur, [col[0] for col in cur.description]))
            return

        print("%s/%s:" % (out_path, lang), flush=True, end=" ")
        for name, f in targets:
            if not only or only == name:
                print(name, flush=True, end=" ")
                f(conn, lang)
        conn.commit()
        if not only and vacuum:
            print("analyze", flush=True, end=" ")
            conn.execute("ANALYZE main")
        print()


def koreader_dict_list():
    """Generate KOReader's downloadable-dictionary list for all built StarDict
    dictionaries, as a self-contained Lua module printed to stdout.

    The module returns a table of dictionary entries. It is meant to be saved
    as KOReader's `frontend/ui/data/dictionaries_wikdict.lua` and merged into
    `dictionaries.lua` with:

        for _, d in ipairs(require("ui/data/dictionaries_wikdict")) do
            table.insert(dictionaries, d)
        end

    Iterates the StarDict dirs that actually exist (so only pairs with a
    published zip are listed) and reads the headword count from each `.ifo`.
    """
    base_url = "https://download.wikdict.com/dictionaries/stardict"
    entries = []
    for ifo in sorted(glob.glob("dictionaries/stardict/wikdict-*/stardict.ifo")):
        pair = os.path.basename(os.path.dirname(ifo))  # e.g. "wikdict-de-en"
        from_lang, to_lang = pair[len("wikdict-") :].split("-")

        wordcount = None
        with open(ifo, encoding="utf-8") as f:
            for line in f:
                if line.startswith("wordcount="):
                    wordcount = int(line.split("=", 1)[1].strip())
                    break

        entries.append(
            {
                "name": "%s-%s (WikDict)"
                % (language_names[from_lang], language_names[to_lang]),
                "lang_in": language_codes3[from_lang],
                "lang_out": language_codes3[to_lang],
                "entries": wordcount,
                "url": "%s/%s.zip" % (base_url, pair),
            }
        )

    entries.sort(key=lambda e: e["name"])

    print("-- WikDict bilingual dictionaries for KOReader.")
    print(
        "-- Generated by wikdict-gen: `python3 src/helper.py koreader`. Do not edit by hand."
    )
    print("-- Source: WikDict (Wiktionary via DBnary, https://www.wikdict.com).")
    print("-- License: CC BY-SA 4.0.")
    print("return {")
    for e in entries:
        print("    {")
        print('        name = "%s",' % e["name"])
        print('        lang_in = "%s",' % e["lang_in"])
        print('        lang_out = "%s",' % e["lang_out"])
        print("        entries = %d," % e["entries"])
        print('        license = "CC BY-SA 4.0",')
        print('        url = "%s",' % e["url"])
        print("    },")
    print("}")


BASELINE_PATH = "src/tests/translation_baseline.tsv"


def translation_stats():
    """Per source edition: ``(definition_ratio, total_translations)``, summed
    across all of the edition's raw pairs.

    The *ratio* is the fraction of translations carrying a sense definition (the
    high-quality path, ``translation_sense``) rather than only a gloss hint; the
    sense<->translation linkage drifts per edition in dbnary, so a per-edition
    ratio catches a linkage collapse (e.g. a query that silently stops matching).
    The *count* catches the orthogonal failure the ratio is blind to: an edition
    (or the upstream dump) shedding most of its translations while the ratio holds
    steady -- e.g. the 2026-06 Malagasy edition lost ~80% of its translations
    (mg-en 1917 -> 358) yet its already-~0 ratio never moved, silently pushing
    en-mg below the publish thresholds.
    """
    linked = {}
    total = {}
    for path in glob.glob("dictionaries/raw/*-*.sqlite3"):
        src = os.path.basename(path).split("-")[0]
        with closing(sqlite3.connect(path)) as conn:
            try:
                n_sense = conn.execute(
                    "SELECT count(*) FROM translation_sense"
                ).fetchone()[0]
                n_total = conn.execute("SELECT count(*) FROM translation").fetchone()[0]
            except sqlite3.OperationalError:
                continue  # pair not built yet / tables missing
        linked[src] = linked.get(src, 0) + n_sense
        total[src] = total.get(src, 0) + n_total
    return {
        src: (linked[src] / total[src], total[src]) for src in total if total[src]
    }


def check_translations(rel_drop=0.5, ratio_floor=0.01, count_floor=200):
    """Flag source editions whose definition ratio *or* translation count
    collapsed vs the baseline.

    Two regressions hide from the empty-db check, both caught here:
    1. The edition loses its sense<->translation linkage -- the gloss path keeps
       ``translation`` non-empty, so only the *ratio* of definition-bearing rows
       drops.
    2. The edition (or upstream dump) sheds most of its translations -- the
       *count* drops while the ratio is unchanged. This is the 2026-06 Malagasy
       collapse (every mg-* pair ~-80%) that pushed en-mg out of the downloads
       and the web picker with no error anywhere.

    Editions legitimately near zero are excluded by the floors so they can't
    false-positive; a real regression trips ``rel_drop``. Regenerate the baseline
    after an intentional change with::

        uv run src/helper.py translation-baseline > src/tests/translation_baseline.tsv
    """
    if not os.path.exists(BASELINE_PATH):
        print(
            f"No translation baseline at {BASELINE_PATH}; skipping "
            f"(create it with `uv run src/helper.py translation-baseline > {BASELINE_PATH}`)"
        )
        return
    baseline = {}
    with open(BASELINE_PATH) as f:
        for line in f:
            if line.strip():
                ed, ratio, count = line.split()
                baseline[ed] = (float(ratio), int(count))
    current = translation_stats()
    bad = []
    for ed, (base_ratio, base_count) in baseline.items():
        cur_ratio, cur_count = current.get(ed, (0.0, 0))
        if base_ratio >= ratio_floor and cur_ratio < base_ratio * rel_drop:
            bad.append(f"{ed} definition-ratio {base_ratio:.1%} -> {cur_ratio:.1%}")
        if base_count >= count_floor and cur_count < base_count * rel_drop:
            bad.append(f"{ed} translation-count {base_count} -> {cur_count}")
    for msg in bad:
        print(f"REGRESSION: {msg}")
    if bad:
        sys.exit(1)
    print("Definition ratios and translation counts ok")


